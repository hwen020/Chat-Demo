import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test('register, stream, reload history, rename and delete', async ({ page }, info) => {
  await page.goto('/')
  if (process.env.CHATFLOW_EXPECT_PUBLIC_DEMO === '1') {
    await expect(page.getByText(/Demo Mode.*Responses are generated by a mock provider/)).toBeVisible()
    expect((await page.request.get('/openapi.json')).status()).toBe(404)
  }
  await page.getByRole('button', { name: 'Create an account' }).click()
  await page.getByLabel('Email').fill(randomUUID() + '@example.test')
  await page.getByLabel('Password').fill('playwright-only-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByText('Mock active')).toBeVisible()
  await page.getByRole('main').getByRole('button', { name: 'New conversation' }).click()
  await page.getByRole('button', { name: 'Rename', exact: true }).click()
  await page.getByLabel('Conversation title').fill('Streaming verification')
  await page.getByRole('button', { name: 'Save' }).click()
  let interrupted = false
  await page.route('**/events?after=*', async route => {
    if (!interrupted) { interrupted = true; return route.abort() }
    return route.continue()
  })
  await page.getByLabel('Message', { exact: true }).fill('Check the flow on ' + info.project.name)
  await page.getByRole('button', { name: 'Send' }).click()
  await expect(page.getByText(/Mock reply for turn 1/)).toBeVisible()
  await expect(page.getByText(/Tell me which part to explore next/)).toBeVisible()
  expect(interrupted).toBe(true)
  await expect(page.getByRole('status')).toHaveCount(0)
  await expect(page).toHaveURL(/\/c\/[\da-f-]+$/i)
  const deepLink = page.url()
  await page.goto(deepLink)
  await expect(page.getByRole('heading', { name: 'Streaming verification' })).toBeVisible()
  await expect(page.getByText(/Mock reply for turn 1/)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.screenshot({ path: info.outputPath('chat.png') })
  const mobile = info.project.name.startsWith('mobile-')
  if (mobile) {
    await page.getByRole('button', { name: 'Open conversations' }).click()
  }
  const history = page.getByRole('navigation', { name: 'Conversation history' })
  const search = page.getByRole('searchbox', { name: 'Search conversations' })
  const conversation = history.getByRole('button', { name: 'Streaming verification' })
  await search.fill('no match')
  await expect(history.getByText('No matching conversations')).toBeVisible()
  await expect(conversation).toHaveCount(0)
  await search.fill('  STREAMING  ')
  await expect(conversation).toBeVisible()
  await conversation.click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Delete conversation' }).click()
  await expect(page.getByRole('heading', { name: 'Start a conversation' })).toBeVisible()
  if (mobile) await page.getByRole('button', { name: 'Open conversations' }).click()
  await expect(history.getByText('No matching conversations')).toBeVisible()
  await search.clear()
  await expect(history.getByText('No matching conversations')).toHaveCount(0)
  if (mobile) await page.getByRole('button', { name: 'Close conversations' }).click()
})


test('edit, regenerate, and restore a soft-deleted conversation', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'Conversation actions use the same workspace on all viewports')
  await page.goto('/')
  await page.getByRole('button', { name: 'Create an account' }).click()
  await page.getByLabel('Email').fill(randomUUID() + '@example.test')
  await page.getByLabel('Password').fill('playwright-only-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await page.getByRole('main').getByRole('button', { name: 'New conversation' }).click()
  await page.getByLabel('Message', { exact: true }).fill('First synthetic prompt')
  await page.getByRole('button', { name: 'Send' }).click()
  await page.getByRole('button', { name: 'Stop reply' }).click()
  await expect(page.getByText('Reply incomplete')).toBeVisible()
  await page.getByRole('button', { name: 'Retry reply' }).click()
  await expect(page.getByRole('button', { name: 'Regenerate' })).toBeEnabled()
  await page.getByRole('button', { name: 'Edit prompt' }).click()
  await page.getByLabel('Edit prompt').fill('Edited synthetic prompt')
  await page.getByRole('button', { name: 'Send edit' }).click()
  await expect(page.locator('.message.assistant .markdown')).toContainText('Edited synthetic prompt')
  await expect(page.getByRole('button', { name: 'Regenerate' })).toBeEnabled()
  await page.getByRole('button', { name: 'Regenerate' }).click()
  await expect(page.getByRole('button', { name: 'Regenerate' })).toBeEnabled()
  await expect(page.locator('.message')).toHaveCount(2)
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Delete conversation' }).click()
  await page.getByRole('button', { name: 'Recently deleted' }).click()
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await expect(page.locator('.message.assistant .markdown')).toContainText('Edited synthetic prompt')
  await page.route('**/v1/conversations/*/messages', async route => {
    const response = await route.fetch()
    const history = await response.json()
    history.messages.at(-1).content = [
      '**Rendered Markdown**',
      '',
      '```typescript',
      'const answer = 42',
      '```',
      '',
      '<span data-raw-markup="true">Raw markup</span>',
      '',
      '![Suppressed image](https://example.test/image.png)',
    ].join('\n')
    await route.fulfill({ response, json: history })
  })
  await page.reload()
  const markdown = page.locator('.message.assistant .markdown')
  await expect(markdown.locator('strong')).toHaveText('Rendered Markdown')
  await expect(markdown.locator('.hljs-keyword')).toHaveText('const')
  await expect(markdown.locator('img, [data-raw-markup]')).toHaveCount(0)

})
